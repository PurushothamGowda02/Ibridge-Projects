import React, { useState } from 'react';
import { useNavigate, Link } from 'react-router-dom';
import { UserPlus, Mail, Lock, User, Loader, ArrowRight, BookOpen, Zap, Users } from 'lucide-react';
import { authApi } from '../../services/authApi';
import { AxiosError } from 'axios';

const Signup = () => {
  const [formData, setFormData] = useState({
    full_name: '',
    email: '',
    password: '',
    role: 'student',
    mobile: ''
  });
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState('');
  const [success, setSuccess] = useState(false);
  const navigate = useNavigate();

  const handleSignup = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsLoading(true);
    setError('');

    try {
      await authApi.register({
        name: formData.full_name,
        email: formData.email,
        password: formData.password,
        role: formData.role,
        mobile: formData.mobile || '0000000000',
      });
      setSuccess(true);
      // Redirect to login where they'll be prompted to take eligibility test
      setTimeout(() => navigate('/login'), 3000);
    } catch (err: unknown) {
      const message = err instanceof AxiosError ? (err.response?.data as { message?: string } | undefined)?.message : undefined;
      setError(message || 'Signup failed. Please try again.');
    } finally {
      setIsLoading(false);
    }
  };

  if (success) {
    return (
      <div className="min-h-screen flex items-center justify-center px-4 bg-[radial-gradient(at_0%_0%,rgba(59,130,246,0.05)_0px,transparent_50%),radial-gradient(at_100%_100%,rgba(168,85,247,0.05)_0px,transparent_50%)]">
        <div className="glass-card max-w-md w-full text-center py-12">
          <div className="bg-green-500/10 w-20 h-20 rounded-full flex items-center justify-center mx-auto mb-6">
            <UserPlus className="text-green-500" size={32} />
          </div>
          <h2 className="text-2xl font-bold mb-2">Account Created Successfully!</h2>
          <p className="text-white/60 mb-6">Your student account is ready. Please login to take the eligibility test before accessing tutorials.</p>
          <Loader className="animate-spin mx-auto text-primary" />
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-[radial-gradient(at_0%_0%,rgba(59,130,246,0.05)_0px,transparent_50%),radial-gradient(at_100%_100%,rgba(168,85,247,0.05)_0px,transparent_50%)]">
      {/* Header */}
      <div className="border-b border-white/10 backdrop-blur-sm sticky top-0 z-50">
        <div className="max-w-7xl mx-auto px-4 py-4 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <BookOpen className="text-primary" size={28} />
            <span className="text-xl font-bold">AI Tutorial LMS</span>
          </div>
          <p className="text-white/60 text-sm">Already registered? <Link to="/login" className="text-primary hover:underline font-semibold">Sign In</Link></p>
        </div>
      </div>

      <div className="max-w-7xl mx-auto px-4 py-12">
        <div className="grid md:grid-cols-2 gap-12 items-center">
          {/* Left Side - Features */}
          <div className="space-y-8">
            <div>
              <h1 className="text-5xl font-extrabold tracking-tight mb-4">
                Start Your <span className="text-primary">Learning</span> Journey
              </h1>
              <p className="text-xl text-white/60">Join thousands of students learning with AI-powered personalized education.</p>
            </div>

            <div className="space-y-6">
              <div className="flex gap-4">
                <div className="flex-shrink-0">
                  <div className="flex items-center justify-center h-12 w-12 rounded-lg bg-primary/20">
                    <Zap className="text-primary" size={24} />
                  </div>
                </div>
                <div>
                  <h3 className="text-lg font-semibold mb-1">AI-Powered Learning</h3>
                  <p className="text-white/60">Personalized courses generated by advanced AI algorithms tailored to your pace.</p>
                </div>
              </div>

              <div className="flex gap-4">
                <div className="flex-shrink-0">
                  <div className="flex items-center justify-center h-12 w-12 rounded-lg bg-primary/20">
                    <BookOpen className="text-primary" size={24} />
                  </div>
                </div>
                <div>
                  <h3 className="text-lg font-semibold mb-1">Comprehensive Courses</h3>
                  <p className="text-white/60">Access hundreds of courses across multiple subjects and skill levels.</p>
                </div>
              </div>

              <div className="flex gap-4">
                <div className="flex-shrink-0">
                  <div className="flex items-center justify-center h-12 w-12 rounded-lg bg-primary/20">
                    <Users className="text-primary" size={24} />
                  </div>
                </div>
                <div>
                  <h3 className="text-lg font-semibold mb-1">Community Support</h3>
                  <p className="text-white/60">Learn together with a supportive community of students and instructors.</p>
                </div>
              </div>
            </div>
          </div>

          {/* Right Side - Registration Form */}
          <div className="glass-card">
            <div className="mb-8">
              <h2 className="text-2xl font-bold mb-2">Create Your Account</h2>
              <p className="text-white/60">Register as a student to get started</p>
            </div>

            <form onSubmit={handleSignup} className="space-y-5">
              <div className="space-y-2">
                <label className="text-sm font-medium text-white/70 ml-1">Full Name</label>
                <div className="relative">
                  <User className="absolute left-4 top-1/2 -translate-y-1/2 text-white/40" size={18} />
                  <input
                    type="text"
                    required
                    placeholder="John Doe"
                    className="input-field w-full pl-12"
                    value={formData.full_name}
                    onChange={(e) => setFormData({ ...formData, full_name: e.target.value })}
                  />
                </div>
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium text-white/70 ml-1">Email Address</label>
                <div className="relative">
                  <Mail className="absolute left-4 top-1/2 -translate-y-1/2 text-white/40" size={18} />
                  <input
                    type="email"
                    required
                    placeholder="name@example.com"
                    className="input-field w-full pl-12"
                    value={formData.email}
                    onChange={(e) => setFormData({ ...formData, email: e.target.value })}
                  />
                </div>
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium text-white/70 ml-1">Password</label>
                <div className="relative">
                  <Lock className="absolute left-4 top-1/2 -translate-y-1/2 text-white/40" size={18} />
                  <input
                    type="password"
                    required
                    placeholder="••••••••"
                    className="input-field w-full pl-12"
                    value={formData.password}
                    onChange={(e) => setFormData({ ...formData, password: e.target.value })}
                  />
                </div>
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium text-white/70 ml-1">Mobile Number</label>
                <div className="relative">
                  <input
                    type="text"
                    required
                    placeholder="9876543210"
                    className="input-field w-full"
                    value={formData.mobile}
                    onChange={(e) => setFormData({ ...formData, mobile: e.target.value })}
                  />
                </div>
              </div>

              {/* Hidden role field - Always set to student */}
              <input type="hidden" value="student" />

              {error && (
                <div className="bg-red-500/10 border border-red-500/20 text-red-500 text-sm p-3 rounded-xl text-center">
                  {error}
                </div>
              )}

              <button type="submit" className="btn-primary w-full flex items-center justify-center gap-2 group" disabled={isLoading}>
                {isLoading ? <Loader className="animate-spin" size={20} /> : (
                  <>
                    Create Student Account <ArrowRight size={18} className="group-hover:translate-x-1 transition-transform" />
                  </>
                )}
              </button>
            </form>

            <p className="text-center mt-6 text-white/50 text-sm">
              By registering, you agree to our Terms of Service and Privacy Policy
            </p>
          </div>
        </div>
      </div>
    </div>
  );
};

export default Signup;
